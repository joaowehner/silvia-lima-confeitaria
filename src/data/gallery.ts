export function getCreationsByCategory(category: string): Creation[] {
  return creations.filter((c) => c.category === category)
}

export function getFeaturedCreations(): Creation[] {
  return creations.filter((c) => c.featured)
}

export function getCreationsByTag(tag: string): Creation[] {
  if (tag === 'Todos') return creations
  return creations.filter((c) =>
    c.tags?.some((t) => t.toLowerCase().includes(tag.toLowerCase()))
  )
}
